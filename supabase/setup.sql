-- 1. TABLES ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    role VARCHAR(20) DEFAULT 'USER' CHECK (role IN ('ADMIN', 'USER')),
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,           -- thêm: khóa tài khoản (PRD 2.3)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.video_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(100) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.videos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    thumbnail_url TEXT,
    video_url TEXT NOT NULL,
    category_id BIGINT REFERENCES public.video_categories(id) ON DELETE SET NULL,
    storage_size_mb DECIMAL(10, 2) DEFAULT 0.00,
    views_count BIGINT DEFAULT 0,
    created_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.video_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    video_id BIGINT REFERENCES public.videos(id) ON DELETE CASCADE,
    view_date DATE NOT NULL DEFAULT CURRENT_DATE,
    views_count INT DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_videos_category ON public.videos(category_id);
CREATE INDEX IF NOT EXISTS idx_videos_created_by ON public.videos(created_by);
CREATE INDEX IF NOT EXISTS idx_video_views_date ON public.video_views(view_date);

-- 2. TRIGGER TẠO PROFILE KHI ĐĂNG KÝ ----------------------------------------
-- LƯU Ý BẢO MẬT: bản trong DATABASE.md đọc role từ raw_user_meta_data, nghĩa là
-- ai cũng có thể tự đăng ký làm ADMIN bằng signUp({options:{data:{role:'ADMIN'}}}).
-- Ở đây luôn gán 'USER'; nâng quyền ADMIN chỉ làm qua SQL hoặc trang Users.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, username, email, role)
  VALUES (
    NEW.id,
    COALESCE(NULLIF(NEW.raw_user_meta_data->>'username', ''), split_part(NEW.email, '@', 1)),
    NEW.email,
    'USER'
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

CREATE OR REPLACE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 3. HELPER FUNCTIONS ---------------------------------------------------------
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'ADMIN' AND is_locked = FALSE
  );
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public;

-- Xóa user (auth.users + cascade profile). Chỉ ADMIN, không tự xóa mình.
CREATE OR REPLACE FUNCTION public.admin_delete_user(target_id UUID)
RETURNS VOID AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Chỉ ADMIN mới được xóa người dùng';
  END IF;
  IF target_id = auth.uid() THEN
    RAISE EXCEPTION 'Không thể tự xóa chính mình';
  END IF;
  DELETE FROM auth.users WHERE id = target_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE ALL ON FUNCTION public.admin_delete_user(UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_delete_user(UUID) TO authenticated;

-- 4. ROW LEVEL SECURITY -------------------------------------------------------
ALTER TABLE public.profiles          ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.video_categories  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.videos            ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.video_views       ENABLE ROW LEVEL SECURITY;

-- profiles: xem profile của mình hoặc ADMIN xem tất cả; chỉ ADMIN được sửa (đổi role/khóa)
DROP POLICY IF EXISTS "profiles_select" ON public.profiles;
CREATE POLICY "profiles_select" ON public.profiles FOR SELECT TO authenticated
  USING (id = auth.uid() OR public.is_admin());
DROP POLICY IF EXISTS "profiles_update_admin" ON public.profiles;
CREATE POLICY "profiles_update_admin" ON public.profiles FOR UPDATE TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

-- video_categories: mọi user đăng nhập được xem; chỉ ADMIN CRUD
DROP POLICY IF EXISTS "categories_select" ON public.video_categories;
CREATE POLICY "categories_select" ON public.video_categories FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "categories_admin_write" ON public.video_categories;
CREATE POLICY "categories_admin_write" ON public.video_categories FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

-- videos: xem tất cả; thêm với created_by = mình; sửa/xóa video của mình hoặc ADMIN
DROP POLICY IF EXISTS "videos_select" ON public.videos;
CREATE POLICY "videos_select" ON public.videos FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "videos_insert" ON public.videos;
CREATE POLICY "videos_insert" ON public.videos FOR INSERT TO authenticated
  WITH CHECK (created_by = auth.uid() OR public.is_admin());
DROP POLICY IF EXISTS "videos_update" ON public.videos;
CREATE POLICY "videos_update" ON public.videos FOR UPDATE TO authenticated
  USING (created_by = auth.uid() OR public.is_admin())
  WITH CHECK (created_by = auth.uid() OR public.is_admin());
DROP POLICY IF EXISTS "videos_delete" ON public.videos;
CREATE POLICY "videos_delete" ON public.videos FOR DELETE TO authenticated
  USING (created_by = auth.uid() OR public.is_admin());

-- video_views: xem tất cả (cho Dashboard); ghi chỉ ADMIN
DROP POLICY IF EXISTS "video_views_select" ON public.video_views;
CREATE POLICY "video_views_select" ON public.video_views FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "video_views_admin_write" ON public.video_views;
CREATE POLICY "video_views_admin_write" ON public.video_views FOR ALL TO authenticated
  USING (public.is_admin()) WITH CHECK (public.is_admin());

-- 5. STORAGE BUCKETS + POLICIES ----------------------------------------------
INSERT INTO storage.buckets (id, name, public) VALUES
  ('thumbnails', 'thumbnails', TRUE),
  ('video_files', 'video_files', TRUE)
ON CONFLICT (id) DO UPDATE SET public = TRUE;

-- Bucket public nên đọc file không cần policy. Upload/xóa: file nằm trong thư mục <user_id>/
DROP POLICY IF EXISTS "media_insert" ON storage.objects;
CREATE POLICY "media_insert" ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id IN ('thumbnails', 'video_files')
    AND ((storage.foldername(name))[1] = auth.uid()::text OR public.is_admin())
  );
DROP POLICY IF EXISTS "media_delete" ON storage.objects;
CREATE POLICY "media_delete" ON storage.objects FOR DELETE TO authenticated
  USING (
    bucket_id IN ('thumbnails', 'video_files')
    AND ((storage.foldername(name))[1] = auth.uid()::text OR public.is_admin())
  );

